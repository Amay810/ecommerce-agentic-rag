"""Framework-neutral trajectory and loss-mask contracts.

The actual token ids and log-probabilities are produced by VERL.  These small
types make the boundary explicit and testable without importing torch/VERL.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Iterable, Literal


Role = Literal["system", "user", "assistant", "tool", "evaluator"]


@dataclass(frozen=True)
class TokenSegment:
    role: Role
    token_ids: tuple[int, ...]


def assistant_only_loss_mask(segments: Iterable[TokenSegment]) -> list[int]:
    """Return 1 only for tokens generated by the trainable agent.

    VERL's multi-turn loop is responsible for obtaining the token ids.  This
    helper is the invariant used by the adapter: system prompts, user-model
    turns, tool observations, and evaluator data never receive policy loss.
    """

    mask: list[int] = []
    for segment in segments:
        mask.extend([1 if segment.role == "assistant" else 0] * len(segment.token_ids))
    return mask


def assert_assistant_only_mask(
    segments: Iterable[TokenSegment], mask: Iterable[int]
) -> None:
    segments = list(segments)
    mask = list(mask)
    expected = assistant_only_loss_mask(segments)
    if mask != expected:
        raise AssertionError(
            "loss mask includes non-agent tokens or misses agent tokens: "
            f"expected={expected}, actual={mask}"
        )


@dataclass
class EpisodeTrajectory:
    run_id: str
    task_id: str
    group_id: str
    rollout_index: int
    policy_version_before: str
    messages: list[dict[str, Any]] = field(default_factory=list)
    response_mask: list[int] = field(default_factory=list)
    reward: float | None = None
    terminated: bool = False
    error: str | None = None

    def set_terminal_reward(self, reward: float) -> None:
        if not self.terminated:
            raise ValueError("terminal reward cannot be assigned before termination")
        if reward not in (0.0, 1.0):
            raise ValueError(f"official reward must be binary, got {reward!r}")
        self.reward = float(reward)
