"""P0 gate: token/cost budget for the full tau3 external evaluation suite.

The v2 plan commits to paired Base/SFT/RL comparisons across several domains at
pass^k. That is a large number of LLM calls from three separate parties per turn
(agent, user simulator, and -- for judge-gated tasks only -- the NL assertion judge).
Discovering the budget at P4 would force dropping arms, which invalidates the paired
design retroactively. So the budget is computed at P0 instead.

Everything here is an explicit model, not a measurement. Task counts and judge
exposure are read from docs/tau3_split_audit.json (generated by
scripts/audit_tau3_retail_split.py). Per-turn token sizes default to rough priors and
should be replaced with `--from-smoke` values once a smoke run exists.

Usage
-----
    python scripts/estimate_tau3_eval_cost.py
    python scripts/estimate_tau3_eval_cost.py --k 4 --arms B0 S1 S2 R1
    python scripts/estimate_tau3_eval_cost.py --from-smoke logs/smoke_tokens.json
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass, asdict
from pathlib import Path

DEFAULT_AUDIT = Path("docs/tau3_split_audit.json")


@dataclass
class TokenPriors:
    """Rough per-call token sizes. Replace with measured values before budgeting."""

    # The retail policy alone is a few thousand tokens and is resent every turn.
    system_prompt_tokens: int = 3500
    tool_schema_tokens: int = 1800
    # Marginal conversation growth per completed turn (agent text + tool result).
    tokens_per_turn_growth: int = 320
    agent_output_tokens: int = 180
    user_sim_prompt_tokens: int = 900
    user_sim_output_tokens: int = 60
    judge_output_tokens: int = 400
    # Turns per task, as a multiple of the reference action count. Agents take
    # detours, ask clarifying questions, and retry, so this exceeds 1.
    turn_multiplier: float = 2.2


@dataclass
class DomainCost:
    domain: str
    split: str
    num_tasks: int
    judge_gated: int
    turns_per_task: float
    agent_prompt_tokens: int
    agent_output_tokens: int
    user_prompt_tokens: int
    user_output_tokens: int
    judge_prompt_tokens: int
    judge_output_tokens: int

    @property
    def total_prompt_tokens(self) -> int:
        return self.agent_prompt_tokens + self.user_prompt_tokens + self.judge_prompt_tokens

    @property
    def total_output_tokens(self) -> int:
        return self.agent_output_tokens + self.user_output_tokens + self.judge_output_tokens


def estimate_split(
    domain: str,
    split: str,
    stats: dict,
    priors: TokenPriors,
    k: int,
) -> DomainCost:
    n = stats["num_tasks"]
    judge_gated = stats["judge_gated_tasks"]
    turns = stats["reference_actions_mean"] * priors.turn_multiplier

    base = priors.system_prompt_tokens + priors.tool_schema_tokens
    # Each turn resends the whole prefix, so prompt cost over a task is the sum of an
    # arithmetic series in conversation length, not base * turns.
    agent_prompt_per_task = sum(
        base + int(priors.tokens_per_turn_growth * t) for t in range(int(turns))
    )
    agent_output_per_task = int(turns) * priors.agent_output_tokens

    # The user simulator sees the conversation but not the tool schemas or policy.
    user_turns = max(1, int(turns / 2))
    user_prompt_per_task = sum(
        priors.user_sim_prompt_tokens + int(priors.tokens_per_turn_growth * t)
        for t in range(user_turns)
    )
    user_output_per_task = user_turns * priors.user_sim_output_tokens

    # The judge is called once per task and only when nl_assertions is non-empty:
    # NLAssertionsEvaluator short-circuits to reward 1.0 otherwise.
    judge_prompt_per_task = base + int(priors.tokens_per_turn_growth * turns)

    runs = n * k
    judge_runs = judge_gated * k

    return DomainCost(
        domain=domain,
        split=split,
        num_tasks=n,
        judge_gated=judge_gated,
        turns_per_task=round(turns, 2),
        agent_prompt_tokens=agent_prompt_per_task * runs,
        agent_output_tokens=agent_output_per_task * runs,
        user_prompt_tokens=user_prompt_per_task * runs,
        user_output_tokens=user_output_per_task * runs,
        judge_prompt_tokens=judge_prompt_per_task * judge_runs,
        judge_output_tokens=priors.judge_output_tokens * judge_runs,
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--audit", type=Path, default=DEFAULT_AUDIT)
    parser.add_argument("--split", default="test")
    parser.add_argument("--domains", nargs="+", default=["retail", "airline", "telecom"])
    parser.add_argument("--arms", nargs="+", default=["B0", "S1", "S2", "R1"])
    parser.add_argument("--k", type=int, default=4, help="rollouts per task for pass^k")
    parser.add_argument(
        "--from-smoke",
        type=Path,
        default=None,
        help="JSON file overriding TokenPriors fields with measured values.",
    )
    parser.add_argument("--out", type=Path, default=Path("docs/tau3_eval_cost_model.json"))
    args = parser.parse_args()

    if not args.audit.exists():
        raise SystemExit(
            f"{args.audit} not found. Run scripts/audit_tau3_retail_split.py first."
        )

    priors = TokenPriors()
    if args.from_smoke:
        measured = json.loads(args.from_smoke.read_text(encoding="utf-8"))
        for key, value in measured.items():
            if hasattr(priors, key):
                setattr(priors, key, value)
            else:
                print(f"[warn] ignoring unknown prior '{key}'")

    audit = json.loads(args.audit.read_text(encoding="utf-8"))

    per_arm: list[DomainCost] = []
    for domain in args.domains:
        stats = audit["domains"][domain]["splits"].get(args.split)
        if stats is None:
            print(f"[warn] {domain} has no '{args.split}' split; skipping")
            continue
        per_arm.append(estimate_split(domain, args.split, stats, priors, args.k))

    num_arms = len(args.arms)
    prompt_one_arm = sum(c.total_prompt_tokens for c in per_arm)
    output_one_arm = sum(c.total_output_tokens for c in per_arm)
    judge_one_arm = sum(c.judge_prompt_tokens + c.judge_output_tokens for c in per_arm)
    tasks_one_arm = sum(c.num_tasks for c in per_arm)

    report = {
        "assumptions": asdict(priors),
        "k": args.k,
        "arms": args.arms,
        "split": args.split,
        "per_domain_per_arm": [asdict(c) for c in per_arm],
        "totals": {
            "external_tasks_per_arm": tasks_one_arm,
            "rollouts_per_arm": tasks_one_arm * args.k,
            "prompt_tokens_per_arm": prompt_one_arm,
            "output_tokens_per_arm": output_one_arm,
            "judge_tokens_per_arm": judge_one_arm,
            "prompt_tokens_all_arms": prompt_one_arm * num_arms,
            "output_tokens_all_arms": output_one_arm * num_arms,
        },
    }

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2), encoding="utf-8")

    print(f"split={args.split}  k={args.k}  arms={num_arms}\n")
    header = f"{'domain':10s} {'tasks':>6s} {'judge':>6s} {'turns':>6s} {'Mprompt':>9s} {'Moutput':>9s}"
    print(header)
    print("-" * len(header))
    for c in per_arm:
        print(
            f"{c.domain:10s} {c.num_tasks:6d} {c.judge_gated:6d} {c.turns_per_task:6.1f} "
            f"{c.total_prompt_tokens / 1e6:9.1f} {c.total_output_tokens / 1e6:9.2f}"
        )
    print("-" * len(header))
    print(
        f"{'per arm':10s} {tasks_one_arm:6d} {'':6s} {'':6s} "
        f"{prompt_one_arm / 1e6:9.1f} {output_one_arm / 1e6:9.2f}"
    )
    print(
        f"{'all arms':10s} {'':6s} {'':6s} {'':6s} "
        f"{prompt_one_arm * num_arms / 1e6:9.1f} {output_one_arm * num_arms / 1e6:9.2f}"
    )
    print(f"\njudge tokens per arm: {judge_one_arm / 1e6:.2f}M")
    print(f"full report: {args.out}")


if __name__ == "__main__":
    main()
